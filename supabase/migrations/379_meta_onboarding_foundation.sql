BEGIN;

DO $$
BEGIN
  IF to_regclass('wacrm.accounts') IS NULL OR
     to_regclass('auth.users') IS NULL OR
     to_regclass('wacrm.whatsapp_config') IS NULL THEN
    RAISE EXCEPTION '379: dependencias ausentes. Migration nao aplicada.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS wacrm.meta_onboarding_integrations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id uuid NOT NULL REFERENCES wacrm.accounts(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 3 AND 80),
  business_id text NOT NULL CHECK (business_id ~ '^[0-9]{5,32}$'),
  app_id text CHECK (app_id IS NULL OR app_id ~ '^[0-9]{5,32}$'),
  access_token_ciphertext text NOT NULL,
  app_secret_ciphertext text,
  source_channel_id uuid REFERENCES wacrm.whatsapp_config(id) ON DELETE SET NULL,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (account_id,id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_meta_onboarding_integration_name
  ON wacrm.meta_onboarding_integrations(account_id, lower(name));
CREATE INDEX IF NOT EXISTS idx_meta_onboarding_integration_account
  ON wacrm.meta_onboarding_integrations(account_id,created_at DESC);

CREATE TABLE IF NOT EXISTS wacrm.meta_onboarding_drafts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id uuid NOT NULL REFERENCES wacrm.accounts(id) ON DELETE CASCADE,
  integration_id uuid NOT NULL,
  waba_id text NOT NULL CHECK (waba_id ~ '^[0-9]{5,32}$'),
  phone_number_id text NOT NULL CHECK (phone_number_id ~ '^[0-9]{5,32}$'),
  display_phone_number text,
  verified_name text,
  former_provider text NOT NULL CHECK (former_provider IN ('fortics','other','new_number')),
  status text NOT NULL DEFAULT 'awaiting_ownership_validation'
    CHECK (status IN ('awaiting_ownership_validation','ready_for_review','blocked','cancelled')),
  attested_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  attested_at timestamptz,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (account_id,phone_number_id),
  FOREIGN KEY (account_id,integration_id)
    REFERENCES wacrm.meta_onboarding_integrations(account_id,id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_meta_onboarding_draft_account
  ON wacrm.meta_onboarding_drafts(account_id,created_at DESC);

CREATE TABLE IF NOT EXISTS wacrm.meta_onboarding_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL REFERENCES wacrm.accounts(id) ON DELETE CASCADE,
  integration_id uuid,
  draft_id uuid,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (action IN ('integration_created','numbers_discovered','draft_created','draft_cancelled')),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (account_id,integration_id)
    REFERENCES wacrm.meta_onboarding_integrations(account_id,id) ON DELETE RESTRICT,
  FOREIGN KEY (account_id,draft_id)
    REFERENCES wacrm.meta_onboarding_drafts(account_id,id) ON DELETE RESTRICT,
  CHECK (pg_catalog.jsonb_typeof(metadata)='object')
);
CREATE INDEX IF NOT EXISTS idx_meta_onboarding_event_account
  ON wacrm.meta_onboarding_events(account_id,occurred_at DESC);

-- Defense-in-depth: frontend nunca recebe tokens via Data API.
-- Sem policies: apenas papeis administrativos do servidor usam essas tabelas.
ALTER TABLE wacrm.meta_onboarding_integrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE wacrm.meta_onboarding_drafts ENABLE ROW LEVEL SECURITY;
ALTER TABLE wacrm.meta_onboarding_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON wacrm.meta_onboarding_integrations,
  wacrm.meta_onboarding_drafts,wacrm.meta_onboarding_events
  FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE ON wacrm.meta_onboarding_integrations TO service_role;
GRANT SELECT,INSERT,UPDATE ON wacrm.meta_onboarding_drafts TO service_role;
GRANT SELECT,INSERT ON wacrm.meta_onboarding_events TO service_role;
GRANT USAGE,SELECT ON SEQUENCE wacrm.meta_onboarding_events_id_seq TO service_role;

DO $$
BEGIN
  IF to_regclass('wacrm.schema_migrations') IS NOT NULL THEN
    INSERT INTO wacrm.schema_migrations(version)
    VALUES ('379_meta_onboarding_foundation')
    ON CONFLICT DO NOTHING;
  END IF;
END $$;
COMMIT;
NOTIFY pgrst,'reload schema';

